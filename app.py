"""AUTOSAR HLD Analysis Assistant - basic Streamlit pilot.

Run with:  streamlit run app.py
"""
import pandas as pd
import streamlit as st

from hld import export, llm, search, store
from hld.ingest import ingest_document

DB_PATH = "hld_store.db"

st.set_page_config(page_title="HLD Analysis Assistant", layout="wide")
st.title("AUTOSAR HLD Analysis Assistant (Pilot)")
st.caption(
    "Evidence-based search over HLD documents. Every answer cites its source. "
    "Engineers must review results before use."
)


@st.cache_resource
def get_conn():
    return store.connect(DB_PATH)


conn = get_conn()

# ---------------- Sidebar: ingestion ----------------
with st.sidebar:
    st.header("1. Ingest documents")
    files = st.file_uploader(
        "HLD files (PDF, TXT, MD)", type=["pdf", "txt", "md"], accept_multiple_files=True
    )
    version = st.text_input("Version label", value="1.0")
    status = st.selectbox(
        "Document status",
        ["approved", "draft"],
        help="Only 'approved' documents are searched by default.",
    )
    if st.button("Ingest", disabled=not files):
        for f in files:
            with st.spinner(f"Processing {f.name}..."):
                _, n_chunks, n_ents, empty = ingest_document(
                    conn, f.name, f.getvalue(), version, status
                )
            st.success(f"{f.name}: {n_chunks} chunks, {n_ents} entity candidates")
            if empty:
                st.warning(
                    f"{f.name}: pages {empty[:10]} contain no text. "
                    "They may be scanned images (OCR is not included in this pilot)."
                )

# ---------------- Main tabs ----------------
tab_docs, tab_ask, tab_entities, tab_export = st.tabs(
    ["Documents", "Ask", "Entities", "Export"]
)

# Documents
with tab_docs:
    docs = store.list_documents(conn)
    if not docs:
        st.info("No documents yet. Upload one in the sidebar.")
    else:
        st.dataframe(pd.DataFrame(docs))
        names = {d["id"]: f"{d['name']} (v{d['version']})" for d in docs}
        del_id = st.selectbox("Delete a document", options=list(names), format_func=names.get)
        if st.button("Delete selected document"):
            store.delete_document(conn, del_id)
            st.rerun()

# Ask
with tab_ask:
    question = st.text_input(
        "Ask a question about the documents",
        placeholder="e.g. Which signal does BrakeCtrl_Swc write?",
    )
    col1, col2 = st.columns(2)
    include_drafts = col1.checkbox("Include draft documents", value=False)
    top_k = col2.slider("Passages to retrieve", 1, 10, 5)

    if question:
        chunks = store.get_chunks(conn, approved_only=not include_drafts)
        hits = search.search(chunks, question, top_k)
        if not hits:
            st.warning("No supporting evidence found. The assistant does not guess.")
        else:
            answer = llm.grounded_answer(question, hits)
            if answer:
                st.markdown(answer)
                st.caption("Generated by the local LLM from the sources below. Verify before use.")
            else:
                st.info("No LLM configured (set LLM_URL). Showing retrieved evidence only.")
                st.text(search.extractive_answer(hits))

            st.subheader("Sources")
            for i, h in enumerate(hits, 1):
                label = (
                    f"[{i}] {h['doc']} v{h['version']} | p.{h['page']} | "
                    f"{h['section']} | score {h['score']:.2f}"
                )
                with st.expander(label, expanded=(i == 1)):
                    st.write(h["text"])

# Entities
with tab_entities:
    ents = store.get_entities(conn)
    if not ents:
        st.info("No entities extracted yet.")
    else:
        df = pd.DataFrame(ents)
        all_kinds = sorted(df["kind"].unique())
        kinds = st.multiselect("Filter by kind", all_kinds, default=all_kinds)
        view = df[df["kind"].isin(kinds)].reset_index(drop=True)
        edited = st.data_editor(
            view,
            disabled=["id", "doc", "version", "kind", "name", "page", "section"],
            column_config={
                "review_status": st.column_config.SelectboxColumn(
                    options=["pending", "confirmed", "rejected"], required=True
                )
            },
            hide_index=True,
            key="entity_editor",
        )
        if st.button("Save review decisions"):
            changed = 0
            for orig, new in zip(view.to_dict("records"), edited.to_dict("records")):
                if orig["review_status"] != new["review_status"]:
                    store.update_review_status(conn, int(new["id"]), new["review_status"])
                    changed += 1
            st.success(f"Saved {changed} change(s).")

# Export
with tab_export:
    ents = store.get_entities(conn)
    docs = store.list_documents(conn)
    st.download_button(
        "Download entity inventory (CSV)",
        data=export.entities_csv(ents),
        file_name="entities.csv",
        mime="text/csv",
    )
    st.download_button(
        "Download full inventory (JSON)",
        data=export.inventory_json(ents, docs),
        file_name="inventory.json",
        mime="application/json",
    )
    st.caption("Exports include review status. Only 'confirmed' entities should be used downstream.")
